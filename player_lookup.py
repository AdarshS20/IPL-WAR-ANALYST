def get_lookup_df() -> pd.DataFrame:
    """
    One row per player name seen in either dict, with columns:
    player, batting_hand, bowling_type. Missing values default to
    "unknown" rather than being dropped, so joins never lose rows.
    """
    names = set(BATTING_HAND) | set(BOWLING_TYPE)
    rows = [
        {
            "player": name,
            "batting_hand": BATTING_HAND.get(name, UNKNOWN),
            "bowling_type": BOWLING_TYPE.get(name, UNKNOWN),
        }
        for name in sorted(names)
    ]
    return pd.DataFrame(rows)
